async function mockWorkspace(page) {
  const data = { projects: [], tasks: [], documents: [], comments: [], activity: [] }
  let failSave = false
  const session = { access_token: 'test-only-token', refresh_token: 'test-only-refresh', token_type: 'bearer', expires_in: 3600, expires_at: Math.floor(Date.now()/1000)+3600, user: { id: owner, email:'test@example.com', aud:'authenticated', role:'authenticated', app_metadata:{},user_metadata:{},created_at:now() } }
  await page.addInitScript(session => localStorage.setItem('prmg-auth-v1',JSON.stringify(session)),session)
  await page.route('https://fgomaujsdblpzxhnnqrg.supabase.co/**', async route => {
    const req = route.request(), url = new URL(req.url())
    const reply = (json,status=200) => route.fulfill({status,contentType:'application/json',body:JSON.stringify(json)})
    if(url.pathname.includes('/rpc/prmg_reorder_task')) {
      if(failSave) return reply({message:'Simulated network save failure'},503)
      const {p_task_id,p_target_id,p_after} = req.postDataJSON()
      const sorted = [...data.tasks].sort((a,b) => a.sort_order == null && b.sort_order == null ? b.created_at.localeCompare(a.created_at) || a.id.localeCompare(b.id) : a.sort_order == null ? -1 : b.sort_order == null ? 1 : a.sort_order-b.sort_order)
      const moved=sorted.find(task=>task.id===p_task_id), rest=sorted.filter(task=>task.id!==p_task_id)
      rest.splice(rest.findIndex(task=>task.id===p_target_id)+(p_after?1:0),0,moved)
      rest.forEach((task,index)=>{task.sort_order=index+1})
      return reply(null)
    }
    if(url.pathname.includes('/rpc/')) return reply(true)
    if(url.pathname.includes('/auth/')) return reply(session)
    const table = url.pathname.split('/').pop().replace('prmg_','')
    if(!data[table]) return reply({message:'Unknown table'},404)
    if(req.method() === 'GET') return reply(data[table])
    if(failSave) return reply({message:'Simulated network save failure'},503)
    const id = url.searchParams.get('id')?.slice(3)
    if(req.method() === 'POST') {
      const row = { id:randomUUID(),created_at:now(),updated_at:now(),...req.postDataJSON() }
      data[table].unshift(row); return reply(row,201)
    }
    const index = data[table].findIndex(r => r.id === id)
    if(req.method() === 'PATCH') { const row = {...data[table][index],...req.postDataJSON(),updated_at:now()}; data[table][index]=row;return reply(row) }
    if(req.method() === 'DELETE') { data[table].splice(index,1); return reply({id}) }
    return reply(null)
  })
  return {data,setFailSave: value => { failSave = value }}
}

