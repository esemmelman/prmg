  const lane = row.locator('.gantt-lane')
  await title.dragTo(lane,{targetPosition:{x:6 * 36 + 18,y:50}})
  await expect.poll(() => data.tasks[0].start_date).toBe(addDays(today(),3))
  expect(data.tasks[0].due_date).toBe(addDays(today(),7))
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await row.locator('.gantt-bar').dragTo(lane,{sourcePosition:{x:18,y:12},targetPosition:{x:8 * 36 + 18,y:50}})
  await expect.poll(() => data.tasks[0].start_date).toBe(addDays(today(),5))
  expect(data.tasks[0].due_date).toBe(addDays(today(),9))
