test('Gantt endpoints resize independently and weekdays align with dates', async ({page}) => {
  const {data,setFailSave} = await mockWorkspace(page)
  const project = {id:randomUUID(),name:'Resize schedule',status:'active',color:'#49755f',created_at:now(),updated_at:now()}
  data.projects.push(project)
  data.tasks.push({id:randomUUID(),project_id:project.id,title:'Resize task',status:'todo',priority:'medium',start_date:today(),due_date:addDays(today(),4),checklist:[],labels:[],created_at:now(),updated_at:now()})
  await page.setViewportSize({width:1600,height:1000})
  await page.goto('./')
  await page.locator('nav').getByRole('button',{name:'Gantt chart',exact:true}).click()
  await expect(page.locator('.gantt-weekdays span')).toHaveCount(30)
  await expect(page.locator('.gantt-weekdays span').nth(3)).toHaveText('SMTWTFS'[new Date(today()+'T12:00:00').getDay()])
  const start = page.getByRole('button',{name:'Change start date for Resize task',exact:true})
  const end = page.getByRole('button',{name:'Change end date for Resize task',exact:true})
  async function resize(handle, days) {
    const rect = await handle.boundingBox()
    await page.mouse.move(rect.x+rect.width/2,rect.y+rect.height/2)
    await page.mouse.down()
    await page.mouse.move(rect.x+rect.width/2+days*36,rect.y+rect.height/2,{steps:5})
    await page.mouse.up()
  }
  await resize(end,2)
  await expect.poll(()=>data.tasks[0].due_date).toBe(addDays(today(),6))
  expect(data.tasks[0].start_date).toBe(today())
  await resize(start,1)
  await expect.poll(()=>data.tasks[0].start_date).toBe(addDays(today(),1))
  expect(data.tasks[0].due_date).toBe(addDays(today(),6))
  await resize(start,-2)
  await expect.poll(()=>data.tasks[0].start_date).toBe(addDays(today(),-1))
  await resize(end,-2)
  await expect.poll(()=>data.tasks[0].due_date).toBe(addDays(today(),4))
  setFailSave(true)
  await resize(end,1)
  await expect(page.getByRole('alert')).toContainText('Could not resize Resize task')
  expect(data.tasks[0].due_date).toBe(addDays(today(),4))
  setFailSave(false)
  await resize(end,-8)
  await expect.poll(()=>data.tasks[0].due_date).toBe(addDays(today(),-1))
  await end.focus()
  await end.press('ArrowRight')
  await expect.poll(()=>data.tasks[0].due_date).toBe(today())
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
